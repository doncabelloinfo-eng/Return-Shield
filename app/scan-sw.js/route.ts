import { NextResponse } from 'next/server';

/**
 * The Scanner's service worker — the minimum Chrome asks for, and not one line
 * more.
 *
 * WHY IT IS SERVED FROM THE ROOT. A service worker may only control pages
 * beneath the directory it is served from, so a script at /scan/sw.js could
 * claim `/scan/` and NOT `/scan` itself — which is the manifest's `start_url`.
 * Served from the root it may claim any scope, and it is registered with
 * `{ scope: '/scan' }`, so it controls the Scanner and nothing else.
 *
 * WHAT IT CACHES: the decoder, and nothing else. `zxing_reader.wasm` is about
 * 950 KB and is needed before the first parcel of the morning can be read, so
 * it is worth having on the phone. Everything else — every page, every API call
 * — falls straight through to the network untouched.
 *
 * WHAT IT MUST NEVER CACHE: anything in the panel. A stale Parcels screen
 * served out of a warehouse phone's cache would be a screen showing yesterday's
 * parcels with no way to tell. The fetch handler returns early for every
 * request that is not the decoder, which is the simplest form that rule can
 * take.
 */
export const dynamic = 'force-static';

const SOURCE = `/* Return Shield Scanner. Generated by app/scan-sw.js/route.ts. */
const CACHE = 'scanner-decoder-v1';
const DECODER = '/zxing_reader.wasm';

self.addEventListener('install', (event) => {
  // Best effort: a decoder that is not cached is a decoder fetched from the
  // network, which is slower and still works.
  event.waitUntil(
    caches.open(CACHE).then((c) => c.add(DECODER)).catch(() => undefined),
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);

  // Everything that is not the decoder goes to the network, untouched and
  // uncached. No page of this app is ever served from here.
  if (event.request.method !== 'GET') return;
  if (url.origin !== self.location.origin) return;
  if (url.pathname !== DECODER) return;

  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(event.request);
      if (hit) return hit;
      const res = await fetch(event.request);
      if (res && res.ok) cache.put(event.request, res.clone());
      return res;
    }),
  );
});
`;

export function GET(): NextResponse {
  return new NextResponse(SOURCE, {
    headers: {
      'Content-Type': 'text/javascript; charset=utf-8',
      // Never cached, so a change here reaches a phone on its next visit
      // rather than whenever the browser feels like it.
      'Cache-Control': 'no-cache',
      // Belt and braces: the script is at the root, so this is already its
      // maximum scope, but saying it makes the intent unmistakable.
      'Service-Worker-Allowed': '/scan',
    },
  });
}
